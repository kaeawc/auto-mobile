package dev.jasonpearson.automobile.protocol

import java.io.ByteArrayOutputStream
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.security.MessageDigest
import java.util.Base64
import java.util.Locale
import java.util.zip.CRC32
import java.util.zip.Deflater
import kotlin.random.Random
import kotlin.test.*
import kotlinx.serialization.json.*
import org.junit.jupiter.api.BeforeAll
import org.junit.jupiter.api.DynamicTest
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.TestFactory

/**
 * Differential and property fuzzing of the bundle import path (#14159). The shared corpus
 * (`fuzz-corpus.json`, generated by `scripts/prototype/generate-bundle-fuzz-corpus.ts`) records the
 * TypeScript verdict for every case; this reader must reproduce accept/reject, code and path. The
 * seeded property tests only assert that `read` never throws and stays fast on hostile input.
 */
class PrototypeBundleFuzzTest {
  /** Case name -> reason. Empty unless a documented, reviewed divergence is being tracked. */
  private val knownDivergences: Map<String, String> = emptyMap()

  companion object {
    private const val SEED = 14159
    private const val CALL_BUDGET_NANOS = 500_000_000L
    private val codes = PrototypeBundleErrorCode.entries.toSet()

    private class FuzzCase(val name: String, val bytes: ByteArray, val value: JsonObject)

    private val fuzzCases: List<FuzzCase> by lazy {
      val relative = "test/fixtures/prototype-bundle/fuzz-corpus.json"
      val file =
        sequenceOf(File(relative), File("../$relative"), File("../../$relative")).first {
          it.isFile
        }
      Json.parseToJsonElement(file.readText())
        .jsonObject
        .getValue("cases")
        .jsonArray
        .map { it.jsonObject }
        .map {
          FuzzCase(
            it.getValue("name").jsonPrimitive.content,
            Base64.getDecoder().decode(it.getValue("bundleBase64").jsonPrimitive.content),
            it,
          )
        }
    }

    @JvmStatic
    @BeforeAll
    fun prepare() {
      // Warm the reader and force corpus decoding outside individual test timing.
      PrototypeBundleReader.read(fuzzCases.first().bytes)
      // Also warm the accept path (spec parse + contract validation), which rejects never reach.
      assertIs<PrototypeBundleReadResult.Success>(PrototypeBundleReader.read(bundle(validSpec)))
    }

    private fun sha(bytes: ByteArray) =
      MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") {
        "%02x".format(Locale.ROOT, it)
      }

    private val validSpec =
      """{"id":"bundle-demo","window":{"placement":{"type":"fullscreen"}},"root":{"type":"text","text":"Hello"}}"""
        .toByteArray()

    private fun manifest(spec: ByteArray) =
      """{"bundleFormatVersion":1,"specSha256":"${sha(spec)}","assets":[],"fonts":[],"requires":[]}"""
        .toByteArray()

    /** A hostile-capable ZIP builder: every header field can lie about the payload. */
    class Part(
      val name: String,
      val data: ByteArray,
      val deflate: Boolean = false,
      val declaredExpanded: Long? = null,
      val externalAttributes: Long = 0,
    )

    fun zip(parts: List<Part>): ByteArray {
      val locals = ByteArrayOutputStream()
      val central = ByteArrayOutputStream()
      for (part in parts) {
        val name = part.name.toByteArray(Charsets.ISO_8859_1)
        val stored = if (part.deflate) deflateRaw(part.data) else part.data
        val crc = CRC32().apply { update(part.data) }.value.toInt()
        val expanded = (part.declaredExpanded ?: part.data.size.toLong()).toInt()
        val method: Short = if (part.deflate) 8 else 0
        locals.write(
          le(30) {
            putInt(0, 0x04034b50)
            putShort(4, 20)
            putShort(8, method)
            putInt(14, crc)
            putInt(18, stored.size)
            putInt(22, expanded)
            putShort(26, name.size.toShort())
          },
        )
        central.write(
          le(46) {
            putInt(0, 0x02014b50)
            putShort(4, 20)
            putShort(6, 20)
            putShort(10, method)
            putInt(16, crc)
            putInt(20, stored.size)
            putInt(24, expanded)
            putShort(28, name.size.toShort())
            putInt(38, part.externalAttributes.toInt())
            putInt(42, locals.size() - 30)
          },
        )
        // Patch the central offset now that the local header has been written.
        locals.write(name)
        central.write(name)
        locals.write(stored)
      }
      return finish(locals, central, parts.size)
    }

    private fun finish(
      locals: ByteArrayOutputStream,
      central: ByteArrayOutputStream,
      n: Int,
    ): ByteArray {
      val out = ByteArrayOutputStream()
      out.write(locals.toByteArray())
      out.write(central.toByteArray())
      out.write(
        le(22) {
          putInt(0, 0x06054b50)
          putShort(8, n.toShort())
          putShort(10, n.toShort())
          putInt(12, central.size())
          putInt(16, locals.size())
        },
      )
      return out.toByteArray()
    }

    private fun le(size: Int, fill: ByteBuffer.() -> Unit): ByteArray =
      ByteBuffer.allocate(size).order(ByteOrder.LITTLE_ENDIAN).apply(fill).array()

    private fun deflateRaw(data: ByteArray): ByteArray {
      val deflater = Deflater(Deflater.BEST_COMPRESSION, true)
      deflater.setInput(data)
      deflater.finish()
      val out = ByteArrayOutputStream()
      val buffer = ByteArray(8192)
      while (!deflater.finished()) out.write(buffer, 0, deflater.deflate(buffer))
      deflater.end()
      return out.toByteArray()
    }

    fun bundle(spec: ByteArray, manifest: ByteArray = manifest(spec)) =
      PrototypeBundleZipWriter.write(linkedMapOf("bundle.json" to manifest, "spec.json" to spec))

    fun read(bytes: ByteArray, label: String): PrototypeBundleReadResult {
      val start = System.nanoTime()
      val result = PrototypeBundleReader.read(bytes)
      val elapsed = System.nanoTime() - start
      assertTrue(elapsed < CALL_BUDGET_NANOS, "$label took ${elapsed / 1_000_000} ms")
      if (result is PrototypeBundleReadResult.Rejected) {
        assertTrue(result.code in codes, "$label produced code outside the vocabulary")
      }
      return result
    }

    fun assertRejected(
      expected: PrototypeBundleErrorCode,
      bytes: ByteArray,
      label: String,
    ): PrototypeBundleReadResult.Rejected {
      val result = assertIs<PrototypeBundleReadResult.Rejected>(read(bytes, label), label)
      assertEquals(expected, result.code, label)
      return result
    }
  }

  @TestFactory
  fun `reader matches every fuzz corpus verdict code and path`(): List<DynamicTest> =
    fuzzCases.map { case ->
      DynamicTest.dynamicTest(case.name) {
        if (case.name in knownDivergences) return@dynamicTest
        val result = read(case.bytes, case.name)
        if (case.value.getValue("expect").jsonPrimitive.content == "accept") {
          assertIs<PrototypeBundleReadResult.Success>(result, case.name)
        } else {
          val failure = assertIs<PrototypeBundleReadResult.Rejected>(result, case.name)
          assertEquals(
            case.value.getValue("code").jsonPrimitive.content,
            failure.code.name,
            case.name,
          )
          assertEquals(case.value["path"]?.jsonPrimitive?.content, failure.path, case.name)
        }
      }
    }

  @Test
  fun `known divergences name real corpus cases`() {
    val names = fuzzCases.map { it.name }.toSet()
    assertTrue(knownDivergences.keys.all { it in names })
  }

  @Test
  fun `seeded byte flips truncations splices and header lies never throw`() {
    val seeds =
      fuzzCases.filter { it.bytes.size in 100..700 }.take(6).map { it.bytes } + bundle(validSpec)
    val random = Random(SEED)
    val lies = longArrayOf(0, 0xffffffffL, 0x7fffffffL, 0x80000000L, 0xffffL, 1)
    repeat(120) { iteration ->
      val base = seeds[random.nextInt(seeds.size)]
      val mutated =
        when (random.nextInt(5)) {
          0 -> base.copyOf().also { it[random.nextInt(it.size)] = random.nextInt(256).toByte() }
          1 -> base.copyOf(random.nextInt(base.size + 1))
          2 -> {
            val other = seeds[random.nextInt(seeds.size)]
            val cut = random.nextInt(base.size)
            base.copyOf(cut) + other.copyOfRange(random.nextInt(other.size), other.size)
          }
          3 ->
            base.copyOf().also { bytes ->
              val at = random.nextInt(bytes.size - 3)
              val value = lies[random.nextInt(lies.size)]
              for (i in 0..3) bytes[at + i] = (value shr (8 * i)).toByte()
            }
          else ->
            base.copyOf().also { bytes ->
              // Aim at the 22-byte end-of-directory record, where the counts and offsets live.
              val at = bytes.size - 1 - random.nextInt(minOf(22, bytes.size))
              bytes[at] = (bytes[at].toInt() xor (1 shl random.nextInt(8))).toByte()
            }
        }
      read(mutated, "mutation $iteration")
    }
  }

  @Test
  fun `random bytes and tiny inputs are rejected as not a zip`() {
    val random = Random(SEED)
    assertRejected(PrototypeBundleErrorCode.not_a_zip, ByteArray(0), "empty")
    repeat(8) { n ->
      val bytes = random.nextBytes(random.nextInt(1, 600))
      assertIs<PrototypeBundleReadResult.Rejected>(read(bytes, "random $n"), "random $n")
    }
  }

  @Test
  fun `declared deflate bomb is rejected before inflation`() {
    val data = ByteArray(16 * 1024 * 1024)
    val bytes = zip(listOf(Part("spec.json", data, deflate = true)))
    assertRejected(PrototypeBundleErrorCode.entry_too_large, bytes, "16 MiB bomb")
  }

  @Test
  fun `lying deflate header cannot expand past the budget`() {
    // Header claims a small spec; the stream inflates to 4 MiB of zeros from a few KiB.
    val bomb =
      zip(listOf(Part("spec.json", ByteArray(4 * 1024 * 1024), true, declaredExpanded = 64)))
    val rejected = assertIs<PrototypeBundleReadResult.Rejected>(read(bomb, "lying bomb"))
    assertTrue(
      rejected.code in
        setOf(
          PrototypeBundleErrorCode.ratio_exceeded,
          PrototypeBundleErrorCode.entry_too_large,
          PrototypeBundleErrorCode.size_mismatch,
        ),
      rejected.code.name,
    )
    assertEquals("spec.json", rejected.path)
  }

  @Test
  fun `compression ratio over the cap is rejected`() {
    // 1 MiB (the spec cap) of zeros deflates to ~1 KiB: a ratio far above the 100x limit.
    val bytes =
      zip(listOf(Part("spec.json", ByteArray(PrototypeBundleLimits.MAX_SPEC_BYTES), true)))
    assertRejected(PrototypeBundleErrorCode.ratio_exceeded, bytes, "ratio bomb")
  }

  @Test
  fun `hostile entry names links duplicates and oversize entries reject`() {
    val manifest = manifest(validSpec)
    fun with(extra: Part) = zip(listOf(Part("bundle.json", manifest), extra))
    val forbidden =
      listOf("../spec.json", "/spec.json", "a/../spec.json", "sp\\ec.json", "__MACOSX/spec.json")
    for (name in forbidden) {
      assertRejected(
        PrototypeBundleErrorCode.entry_name_forbidden,
        with(Part(name, validSpec)),
        name,
      )
    }
    assertRejected(
      PrototypeBundleErrorCode.entry_not_allowed,
      with(Part("notes.txt", validSpec)),
      "unlisted name",
    )
    assertRejected(
      PrototypeBundleErrorCode.link_entry,
      with(Part("spec.json", validSpec, externalAttributes = 0xA1FF0000L)),
      "symlink",
    )
    assertRejected(
      PrototypeBundleErrorCode.duplicate_entry,
      zip(listOf(Part("spec.json", validSpec), Part("spec.json", validSpec))),
      "duplicate",
    )
    assertRejected(
      PrototypeBundleErrorCode.duplicate_entry,
      zip(listOf(Part("spec.json", validSpec), Part("SPEC.json", validSpec))),
      "case-folded duplicate",
    )
    val oversize = ByteArray(PrototypeBundleLimits.MAX_SPEC_BYTES + 1) { 'a'.code.toByte() }
    assertRejected(
      PrototypeBundleErrorCode.entry_too_large,
      with(Part("spec.json", oversize)),
      "oversize spec",
    )
    val many =
      (0..PrototypeBundleLimits.MAX_ENTRIES).map {
        Part("assets/${"%064x".format(Locale.ROOT, it)}.png", ByteArray(1))
      }
    assertRejected(PrototypeBundleErrorCode.too_many_entries, zip(many), "too many entries")
  }

  @Test
  fun `hostile JSON documents reject without throwing`() {
    fun spec(text: ByteArray) = read(bundle(text), "json").let { it }
    fun nested(depth: Int) = ("[".repeat(depth) + "]".repeat(depth)).toByteArray()
    for (depth in listOf(63, 64, 65)) {
      val result = assertIs<PrototypeBundleReadResult.Rejected>(spec(nested(depth)), "depth $depth")
      assertEquals(PrototypeBundleErrorCode.spec_invalid, result.code, "depth $depth")
    }
    for (depth in listOf(66, 5000, 100_000)) {
      val result = assertIs<PrototypeBundleReadResult.Rejected>(spec(nested(depth)), "depth $depth")
      assertEquals(PrototypeBundleErrorCode.spec_invalid_json, result.code, "depth $depth")
    }
    val deepObject = "{\"a\":".repeat(5000) + "1" + "}".repeat(5000)
    assertEquals(
      PrototypeBundleErrorCode.spec_invalid_json,
      assertIs<PrototypeBundleReadResult.Rejected>(spec(deepObject.toByteArray())).code,
    )
    val invalid =
      listOf(
        "invalid utf-8 lead" to
          byteArrayOf(0x7b, 0x22, 0xc3.toByte(), 0x28, 0x22, 0x3a, 0x31, 0x7d),
        "overlong" to byteArrayOf(0x7b, 0x22, 0xc0.toByte(), 0xaf.toByte(), 0x22, 0x3a, 0x31, 0x7d),
        "encoded surrogate" to byteArrayOf(0x22, 0xed.toByte(), 0xa0.toByte(), 0x80.toByte(), 0x22),
        "duplicate keys" to """{"id":"a","id":"b"}""".toByteArray(),
        "nan" to """{"id":NaN}""".toByteArray(),
        "trailing comma" to """{"id":"a",}""".toByteArray(),
        "huge exponent" to """{"id":1e999999999}""".toByteArray(),
        "huge integer" to """{"id":${"9".repeat(5000)}}""".toByteArray(),
        "empty" to ByteArray(0),
        "nul" to byteArrayOf(0),
      )
    for ((label, text) in invalid) {
      val result = assertIs<PrototypeBundleReadResult.Rejected>(spec(text), label)
      assertTrue(
        result.code in
          setOf(
            PrototypeBundleErrorCode.spec_invalid_json,
            PrototypeBundleErrorCode.spec_invalid,
          ),
        "$label -> ${result.code}",
      )
    }
    val lone = """{"id":"bundle-demo\ud800","window":{},"root":{}}""".toByteArray()
    assertIs<PrototypeBundleReadResult.Rejected>(spec(lone), "lone escaped surrogate")
    // A BOM is tolerated or rejected, never a crash; a valid spec behind one must not throw.
    read(bundle(byteArrayOf(0xef.toByte(), 0xbb.toByte(), 0xbf.toByte()) + validSpec), "bom")
    assertIs<PrototypeBundleReadResult.Success>(read(bundle(validSpec), "baseline"))
  }

  @Test
  fun `seeded structural spec mutations never throw`() {
    val random = Random(SEED + 1)
    val text = validSpec.toString(Charsets.UTF_8)
    val tokens =
      listOf("{", "}", "[", "]", "\"", ",", ":", "\\", "\\u", "null", "1e400", "-0", "\uD800")
    repeat(100) { iteration ->
      val at = random.nextInt(text.length)
      val mutated =
        when (random.nextInt(3)) {
          0 -> text.removeRange(at, minOf(text.length, at + random.nextInt(1, 6)))
          1 -> text.substring(0, at) + tokens[random.nextInt(tokens.size)] + text.substring(at)
          else -> text.replaceRange(at, at + 1, tokens[random.nextInt(tokens.size)])
        }
      read(bundle(mutated.toByteArray()), "spec mutation $iteration")
    }
  }
}
