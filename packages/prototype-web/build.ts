// Bundles the prototype web renderer from src/features/prototype/web/ into dist/index.js, and the
// <automobile-prototype> element over it into dist/element.js, for the browser (#16453, #16454). Run from this directory: `bun run build`. Nothing is installed here; the
// bundle inlines everything it reaches, so the package has no dependencies.
//
// `--outdir <dir>` writes the two library entries there instead of dist/, and `--library` skips
// the page module below: the release stages the package in a temporary copy this way, so packing
// it never touches the checkout (#16455).
//
// It also writes the page entry's build to src/features/prototype/web/prototypeWebPageBundle.generated.ts
// (#16528), the one script the server's prototype web page inlines. That file is committed, and
// prototypeWebPageBundle.test.ts fails when it differs from a fresh build. `bun build.ts --check`
// runs the same comparison.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = (path: string) => fileURLToPath(new URL(path, import.meta.url));

/** The package's entry points; each bundles on its own, so `element` and `page` hold `mount` too. */
export type PrototypeWebEntry = "index" | "element" | "page";

/** One budget per export: its HTML, JS and CSS counted together, minified; no gzip limit. */
export const MAX_PROTOTYPE_WEB_EXPORT_BYTES = 500_000;

/** Throws when an export's minified HTML, JS and CSS together cross the budget. */
export function assertPrototypeWebExportBudget(name: string, bytes: number): void {
  if (bytes > MAX_PROTOTYPE_WEB_EXPORT_BYTES) {
    throw new Error(
      `prototype-web ${name} is ${bytes} bytes minified, over the ${MAX_PROTOTYPE_WEB_EXPORT_BYTES}-byte export budget`,
    );
  }
}

/**
 * Stands in for the root package.json version in the committed page bundle, so a release's
 * version bump does not make it stale; the server swaps in the real version when it reads it.
 */
export const PROTOTYPE_WEB_PAGE_VERSION_MARK = "0.0.0-automobile-page-bundle";

export const prototypeWebPageBundlePath =
  "src/features/prototype/web/prototypeWebPageBundle.generated.ts";

const rootManifest = here("../../package.json");

/** Bundles the root manifest as its version mark only, for the page entry. */
const versionMark: Bun.BunPlugin = {
  name: "page-bundle-version-mark",
  setup(build) {
    build.onLoad({ filter: /package\.json$/ }, (args) =>
      resolve(args.path) === resolve(rootManifest)
        ? {
            contents: `export const version = ${JSON.stringify(PROTOTYPE_WEB_PAGE_VERSION_MARK)};`,
            loader: "js",
          }
        : { contents: readFileSync(args.path, "utf8"), loader: "json" },
    );
  },
};

/** The library bundle's source; the screenshot check loads the same build. */
export async function buildPrototypeWebLibrary(
  outdir?: string,
  entry: PrototypeWebEntry = "index",
): Promise<string> {
  const result = await Bun.build({
    entrypoints: [here(`./src/${entry}.ts`)],
    ...(outdir ? { outdir } : {}),
    naming: `${entry}.js`,
    target: "browser",
    format: "esm",
    minify: true,
    ...(entry === "page" ? { plugins: [versionMark] } : {}),
  });
  if (!result.success) {
    throw new AggregateError(result.logs, "prototype-web build failed");
  }
  return result.outputs[0].text();
}

/** The committed module holding the page bundle; LF line endings, whatever the platform. */
export function renderPrototypeWebPageBundleModule(code: string): string {
  return [
    "// Generated by packages/prototype-web/build.ts from packages/prototype-web/src/page.ts; do not edit.",
    "// Regenerate: cd packages/prototype-web && bun run build",
    "",
    "/** The minified page bundle; its root package.json version is the mark below. */",
    `export const PROTOTYPE_WEB_PAGE_BUNDLE_SOURCE: string = ${JSON.stringify(code)};`,
    "",
    "/** Where the bundle names its library version; the server replaces it with the real one. */",
    `export const PROTOTYPE_WEB_PAGE_BUNDLE_VERSION_MARK: string = ${JSON.stringify(PROTOTYPE_WEB_PAGE_VERSION_MARK)};`,
    "",
  ].join("\n");
}

/** A fresh build of the page module, refused when the bundle is over the export budget. */
export async function buildPrototypeWebPageBundleModule(): Promise<string> {
  const code = await buildPrototypeWebLibrary(undefined, "page");
  assertPrototypeWebExportBudget("page", Buffer.byteLength(code));
  return renderPrototypeWebPageBundleModule(code);
}

if (import.meta.main) {
  const pagePath = here(`../../${prototypeWebPageBundlePath}`);
  if (process.argv.includes("--check")) {
    const pageModule = await buildPrototypeWebPageBundleModule();
    if (readFileSync(pagePath, "utf8").replace(/\r\n/g, "\n") !== pageModule) {
      console.error(
        `${prototypeWebPageBundlePath} is stale; regenerate: cd packages/prototype-web && bun run build`,
      );
      process.exitCode = 1;
    }
  } else {
    const outdirAt = process.argv.indexOf("--outdir");
    const outdir = outdirAt === -1 ? here("./dist") : resolve(process.argv[outdirAt + 1] ?? "");
    for (const entry of ["index", "element"] as const) {
      const code = await buildPrototypeWebLibrary(outdir, entry);
      assertPrototypeWebExportBudget(entry, Buffer.byteLength(code));
      console.log(
        `prototype-web: ${outdir}/${entry}.js, ${Buffer.byteLength(code)} bytes minified`,
      );
    }
    if (!process.argv.includes("--library")) {
      const pageModule = await buildPrototypeWebPageBundleModule();
      writeFileSync(pagePath, pageModule);
      console.log(
        `prototype-web: ${prototypeWebPageBundlePath}, ${Buffer.byteLength(pageModule)} bytes`,
      );
    }
  }
}
