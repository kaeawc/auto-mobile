#!/usr/bin/env bash
# Summarize opt-in Compose compiler stability reports.
# Usage: compose-compiler-report.sh [--reports-dir DIR] [--package PREFIX] [--write-doc FILE]
# COMPOSE_REPORT_GRADLEW overrides the Gradle wrapper executable.
set -euo pipefail
export LC_ALL=C
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
usage() { sed -n '2,4p' "${BASH_SOURCE[0]}" | sed 's/^# //'; }
die() { echo "compose-compiler-report: $*" >&2; exit 2; }
reports="${REPO_ROOT}/android/control-proxy/build/compose-compiler-reports"
package=dev.jasonpearson.automobile.ctrlproxy.prototype
doc=""; compile=true
while [[ $# -gt 0 ]]; do
  case "$1" in
    --help|-h) usage; exit 0 ;;
    --reports-dir|--package|--write-doc)
      [[ $# -ge 2 ]] || die "$1 needs a value"
      case "$1" in
        --reports-dir) reports="$2"; compile=false ;;
        --package) package="$2" ;;
        --write-doc) doc="$2" ;;
      esac
      shift 2 ;;
    *) die "unknown option: $1" ;;
  esac
done
if $compile; then
  (cd "${REPO_ROOT}/android" && "${COMPOSE_REPORT_GRADLEW:-${REPO_ROOT}/android/gradlew}" :control-proxy:compileReleaseKotlin --rerun -Pautomobile.composeCompilerReports=true) >&2
fi
composables="${reports}/control-proxy-composables.txt"
module="${reports}/release/control-proxy-module.json"
[[ -f "$composables" ]] || die "missing report: control-proxy-composables.txt"
[[ -f "$module" ]] || die "missing report: release/control-proxy-module.json"
# Capture order is retained for overloads by the insertion sort in END.
summary=$(awk -v prefix="$package." '
function finish() {
  if (!selected) return
  names[++n]=name; rows[n]="| " name " | " (restart ? "yes" : "no") " | " (skip ? "yes" : "no") " | " (unstable ? unstable : "—") " | " (unmarked ? unmarked : "—") " |"
  r+=restart; s+=skip; ns+=(restart && !skip); u+=(unstable != "")
  selected=0
}
/ fun / || /^fun / {
  finish(); header=$0; sub(/^.*fun /,"",header); sub(/\(.*/,"",header)
  selected=(index(header,prefix)==1); name=header; sub(/^.*\./,"",name)
  restart=($0 ~ /(^| )restartable( |$)/); skip=($0 ~ /(^| )skippable( |$)/)
  unstable=""; unmarked=""
  if ($0 ~ /\(\)/) finish()
  next
}
/^\)/ { finish(); next }
selected && /^  / {
  param=$0; sub(/^ +/,"",param); sub(/ = .*/,"",param)
  marker=""; if (param ~ /^(stable|unstable) /) { marker=param; sub(/ .*/,"",marker); sub(/^[^ ]+ /,"",param) }
  gsub(/\|/,"\\|",param)
  param="`" param "`"
  if (marker=="unstable") unstable=unstable (unstable ? "; " : "") param
  if (marker=="") unmarked=unmarked (unmarked ? "; " : "") param
}
END {
  finish()
  printf "Totals for `%s`: functions listed=%d, restartable=%d, skippable=%d, restartable-but-not-skippable=%d, functions with unstable parameters=%d.\n\n", substr(prefix,1,length(prefix)-1),n,r,s,ns,u
  print "| Function | Restartable | Skippable | Unstable parameters | Parameters with no stability marker |"
  print "| --- | --- | --- | --- | --- |"
  for (i=1;i<=n;i++) order[i]=i
  for (i=2;i<=n;i++) { v=order[i]; j=i-1; while(j>=1 && names[order[j]]>names[v]) {order[j+1]=order[j];j--} order[j+1]=v }
  for(i=1;i<=n;i++) print rows[order[i]]
}' "$composables")
module_summary=$(jq -er '"Module-wide: skippableComposables=\(.skippableComposables), restartableComposables=\(.restartableComposables), knownUnstableArguments=\(.knownUnstableArguments), StrongSkipping=\(.featureFlags.StrongSkipping)."' "$module") || die "invalid module report"
summary="${summary}

${module_summary}"
if [[ -n "$doc" ]]; then
  [[ -d "$(dirname "$doc")" ]] || die "directory not found: $(dirname "$doc")"
  temporary=$(mktemp "${doc}.XXXXXX")
  if ! printf '# Prototype Compose compiler report\nGenerated by scripts/android/compose-compiler-report.sh --write-doc; do not edit by hand.\n\n%s\n' "$summary" > "$temporary"; then
    rm -f "$temporary"
    die "could not write document"
  fi
  if ! mv "$temporary" "$doc"; then
    rm -f "$temporary"
    die "could not replace document"
  fi
fi
printf '%s\n' "$summary"
