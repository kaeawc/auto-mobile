#!/usr/bin/env bun
//
// Generate the devlog index table (docs/devlog/index.md) and the devlog section
// of the MkDocs nav (mkdocs.yml) from the entry files themselves (#19121). Each
// entry's title is its `# ` heading and its kind and date are its `- Kind:` and
// `- Date:` lines, as docs/devlog/template.md lays out. Entries are listed newest
// first: by file name descending, which the `YYYY-MM-DD-` prefix makes date order.
//
// Only the regions between the marker comments are rewritten, so authors add an
// entry file and never hand-edit (or hand-resolve conflicts in) either list.
//
// Usage:
//   bun scripts/docs/generate-devlog-index.ts           # rewrite both regions
//   bun scripts/docs/generate-devlog-index.ts --check   # fail if either is stale

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { load } from "js-yaml";

export const DEVLOG_KINDS = ["decision", "concept", "idea"] as const;
export type DevlogKind = (typeof DEVLOG_KINDS)[number];

export interface DevlogEntry {
  readonly file: string;
  readonly title: string;
  readonly kind: DevlogKind;
  readonly date: string;
}

export const INDEX_START =
  "<!-- devlog-index:start (generated by scripts/docs/generate-devlog-index.ts) -->";
export const INDEX_END = "<!-- devlog-index:end -->";
export const NAV_START = "# devlog-nav:start (generated by scripts/docs/generate-devlog-index.ts)";
export const NAV_END = "# devlog-nav:end";

const ENTRY_FILE = /^(\d{4}-\d{2}-\d{2})-[a-z0-9][a-z0-9-]*\.md$/;
const DATE_PREFIX = /^\d{4}-\d{2}-\d{2}-/;

export function isEntryFile(name: string): boolean {
  return DATE_PREFIX.test(name) && name.endsWith(".md");
}

function metadataLine(source: string, label: string): string | undefined {
  const prefix = `- ${label}:`;
  const line = source.split("\n").find((candidate) => candidate.startsWith(prefix));
  return line?.slice(prefix.length).trim();
}

function isKind(value: string | undefined): value is DevlogKind {
  return DEVLOG_KINDS.some((kind) => kind === value);
}

/** Read one entry's title, kind and date, or throw naming what is wrong. */
export function parseEntry(file: string, source: string): DevlogEntry {
  const name = ENTRY_FILE.exec(file);
  if (!name) {
    throw new Error(`${file}: file name must be YYYY-MM-DD-<lowercase-slug>.md`);
  }
  const firstLine = source.split("\n", 1)[0] ?? "";
  if (!firstLine.startsWith("# ") || firstLine.slice(2).trim() === "") {
    throw new Error(`${file}: first line must be the "# <Title>" heading`);
  }
  const title = firstLine.slice(2).trim();
  const kind = metadataLine(source, "Kind");
  if (!isKind(kind)) {
    throw new Error(
      `${file}: "- Kind:" must be one of ${DEVLOG_KINDS.join(", ")} (found ${kind ?? "none"})`,
    );
  }
  const date = metadataLine(source, "Date");
  if (date !== name[1]) {
    throw new Error(
      `${file}: "- Date:" (${date ?? "none"}) must match the file name date ${name[1]}`,
    );
  }
  return { file, title, kind, date };
}

/** Newest first; the date prefix makes file-name order date order. */
export function sortEntries(entries: readonly DevlogEntry[]): DevlogEntry[] {
  return entries.toSorted((a, b) => (a.file < b.file ? 1 : a.file > b.file ? -1 : 0));
}

function padCell(text: string, width: number): string {
  return text + " ".repeat(Math.max(0, width - Bun.stringWidth(text)));
}

/** The index table, padded the way oxfmt formats a Markdown table. */
export function renderIndexTable(entries: readonly DevlogEntry[]): string {
  const header = ["Date", "Kind", "Entry"];
  const rows = entries.map((entry) => [entry.date, entry.kind, `[${entry.title}](${entry.file})`]);
  const widths = header.map((cell, column) =>
    Math.max(3, Bun.stringWidth(cell), ...rows.map((row) => Bun.stringWidth(row[column] ?? ""))),
  );
  const line = (cells: readonly string[]) =>
    `| ${cells.map((cell, i) => padCell(cell, widths[i] ?? 0)).join(" | ")} |`;
  const divider = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;
  return [line(header), divider, ...rows.map(line)].join("\n");
}

function yamlDoubleQuoted(text: string): string {
  return `"${text.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/** The nav lines for the entries, indented to sit under `- "Devlog":`. */
export function renderNav(entries: readonly DevlogEntry[], indent: string): string {
  return entries
    .map((entry) => {
      const label = yamlDoubleQuoted(`${entry.date}: ${entry.title.replaceAll("`", "")}`);
      return `${indent}- ${label}: devlog/${entry.file}`;
    })
    .join("\n");
}

/** Replace the lines strictly between the start and end marker lines. */
export function replaceRegion(
  source: string,
  start: string,
  end: string,
  body: string,
  label: string,
): string {
  const lines = source.split("\n");
  const startIndex = lines.findIndex((line) => line.trim() === start);
  const endIndex = lines.findIndex((line, i) => i > startIndex && line.trim() === end);
  if (startIndex < 0 || endIndex < 0) {
    throw new Error(`${label}: missing the "${start}" / "${end}" marker lines`);
  }
  return [
    ...lines.slice(0, startIndex + 1),
    ...(body === "" ? [] : body.split("\n")),
    ...lines.slice(endIndex),
  ].join("\n");
}

function markerIndent(source: string, marker: string, label: string): string {
  const line = source.split("\n").find((candidate) => candidate.trim() === marker);
  if (line === undefined) {
    throw new Error(`${label}: missing the "${marker}" marker line`);
  }
  return line.slice(0, line.length - line.trimStart().length);
}

export function renderIndexFile(source: string, entries: readonly DevlogEntry[]): string {
  return replaceRegion(
    source,
    INDEX_START,
    INDEX_END,
    // Blank lines keep the marker comments out of the table (and oxfmt-clean).
    `\n${renderIndexTable(entries)}\n`,
    "docs/devlog/index.md",
  );
}

function navEntryPaths(navValue: unknown): string[] {
  if (!Array.isArray(navValue)) {
    return [];
  }
  const section = navValue.find(
    (item): item is { Devlog: unknown } =>
      typeof item === "object" && item !== null && "Devlog" in item,
  );
  const children = section && Array.isArray(section.Devlog) ? section.Devlog : [];
  return children.flatMap((child: unknown) =>
    typeof child === "object" && child !== null
      ? Object.values(child).filter((v) => typeof v === "string")
      : [],
  );
}

/**
 * Rewrite the mkdocs.yml devlog region, then confirm with a YAML parse that the
 * "Devlog" nav section lists every entry in order, so a marker moved out of
 * that section cannot pass.
 */
export function renderMkdocsFile(source: string, entries: readonly DevlogEntry[]): string {
  const indent = markerIndent(source, NAV_START, "mkdocs.yml");
  const next = replaceRegion(source, NAV_START, NAV_END, renderNav(entries, indent), "mkdocs.yml");
  // mkdocs.yml carries !!python tags js-yaml cannot construct; they are not nav
  // data, so drop only the tag annotation, as validate-mkdocs-nav.ts does.
  const parsed: unknown = load(next.replace(/!!python\/name:\S+/g, ""), { filename: "mkdocs.yml" });
  const nav =
    typeof parsed === "object" && parsed !== null && "nav" in parsed ? parsed.nav : undefined;
  const listed = navEntryPaths(nav).filter((path) => isEntryFile(path.replace(/^devlog\//, "")));
  const expected = entries.map((entry) => `devlog/${entry.file}`);
  if (listed.join("\n") !== expected.join("\n")) {
    throw new Error('mkdocs.yml: the devlog markers must sit inside the "Devlog" nav section');
  }
  return next;
}

export interface DevlogSources {
  readonly entries: ReadonlyArray<{ readonly file: string; readonly source: string }>;
  readonly index: string;
  readonly mkdocs: string;
}

export interface DevlogOutputs {
  readonly index: string;
  readonly mkdocs: string;
}

export function generate(sources: DevlogSources): DevlogOutputs {
  const entries = sortEntries(sources.entries.map(({ file, source }) => parseEntry(file, source)));
  return {
    index: renderIndexFile(sources.index, entries),
    mkdocs: renderMkdocsFile(sources.mkdocs, entries),
  };
}

function readSources(root: string): DevlogSources {
  const devlogDir = join(root, "docs", "devlog");
  const files = readdirSync(devlogDir).filter(isEntryFile);
  return {
    entries: files.map((file) => ({ file, source: readFileSync(join(devlogDir, file), "utf8") })),
    index: readFileSync(join(devlogDir, "index.md"), "utf8"),
    mkdocs: readFileSync(join(root, "mkdocs.yml"), "utf8"),
  };
}

function main(argv: readonly string[]): number {
  const root = join(import.meta.dir, "..", "..");
  const check = argv.includes("--check");
  const sources = readSources(root);
  let outputs: DevlogOutputs;
  try {
    outputs = generate(sources);
  } catch (error) {
    console.error(`error: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }
  const targets = [
    {
      path: join(root, "docs", "devlog", "index.md"),
      label: "docs/devlog/index.md",
      before: sources.index,
      after: outputs.index,
    },
    {
      path: join(root, "mkdocs.yml"),
      label: "mkdocs.yml",
      before: sources.mkdocs,
      after: outputs.mkdocs,
    },
  ];
  const stale = targets.filter((target) => target.before !== target.after);
  if (check) {
    for (const target of stale) {
      console.error(
        `error: ${target.label} devlog list is stale; run bun scripts/docs/generate-devlog-index.ts`,
      );
    }
    return stale.length === 0 ? 0 : 1;
  }
  for (const target of stale) {
    writeFileSync(target.path, target.after);
    console.log(`updated ${target.label}`);
  }
  return 0;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
