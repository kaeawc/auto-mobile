/** Pure registry comparison, sharing the conformance test's existing scan. */
export function productEnvClassificationIssues(
  reads: ReadonlySet<string>,
  paths: readonly string[],
  nonPaths: readonly string[],
): { missing: string[]; overlap: string[]; stale: string[] } {
  const canonical = new Set([...reads].map((name) => name.replace(/^AUTO_MOBILE_/, "AUTOMOBILE_")));
  const registered = new Set(paths);
  const other = new Set(nonPaths);
  return {
    missing: [...canonical].filter((name) => !registered.has(name) && !other.has(name)).sort(),
    overlap: paths.filter((name) => other.has(name)).sort(),
    stale: [...paths, ...nonPaths].filter((name) => !canonical.has(name)).sort(),
  };
}
