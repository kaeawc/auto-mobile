// Literal declarations are intentionally independent of Kotlin's generated descriptors.
// Every property (including inherited properties) and its optionality is checked by tsgo.
// Request markers additionally encode exactly whether the TS field admits null.
type WireFields<T, K extends keyof T = keyof T> = {
  [F in K]-?: undefined extends T[F] ? "optional" : "required";
};

type RequestWireFields<T, K extends keyof T = keyof T> = {
  [
    F in K
  ]-?: `${undefined extends T[F] ? "optional" : "required"}${null extends T[F] ? "_nullable" : ""}`;
};

