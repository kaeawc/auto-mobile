/**
 * `automobile:prototype/{id}/compose` and `.../swiftui` (#16345): one source file per prototype,
 * rendered by the same host-file template as `automobile:prototype/native` with the spec inlined.
 */
export type PrototypeSourceFormat = "compose" | "swiftui";

interface SourceFormat {
  readonly platform: NativePrototypePlatform;
  readonly mimeType: string;
  readonly render: (input: HostFileInput) => string;
}

const FORMATS: Record<PrototypeSourceFormat, SourceFormat> = {
  compose: { platform: "android", mimeType: "text/x-kotlin", render: renderComposeHostFile },
  swiftui: { platform: "ios", mimeType: "text/x-swift", render: renderSwiftUiHostFile },
};

export function prototypeSourceMimeType(format: PrototypeSourceFormat): string {
  return FORMATS[format].mimeType;
}

/** Query parameters of a single-file resource, the id already decoded. */
export interface PrototypeSourceResourceQuery {
  readonly id: string;
  readonly frame?: string;
  readonly revision?: string;
}

export interface PrototypeSourceResourceMeta {
  readonly revision: number;
  readonly deviceRevision?: number;
  /** Kept revisions of the id, oldest first. */
  readonly revisions: readonly number[];
  readonly frame: string;
  readonly sha256: string;
  readonly rendererVersion: string;
}

export interface PrototypeSourceResource {
  readonly text: string;
  readonly mimeType: string;
  readonly meta: PrototypeSourceResourceMeta;
}

interface SourceAsset extends HostFileAsset {
  readonly uri: string;
}

/** Referenced assets by id; the file loads them from the app bundle, never inline. */
function sourceAssets(
  platform: NativePrototypePlatform,
  id: string,
  spec: ShownSpecJson,
): SourceAsset[] {
  const directory = prototypeDirectoryName(id);
  return referencedAssets(spec).map(({ id: assetId, kind }) => ({
    id: assetId,
    kind,
    path: assetPath(platform, directory, prototypeAssetFileStem(assetId)),
    uri: `${PROTOTYPE_NATIVE_ASSET_URI}?${new URLSearchParams({ id, assetId }).toString()}`,
  }));
}

function libraryLine(coordinate: NativePrototypeLibrary): string {
  if ("gradle" in coordinate) {
    return `Library (Gradle): implementation("${coordinate.gradle}")`;
  }
  const { url, from, product } = coordinate.swiftPackage;
  return `Library (SwiftPM): .package(url: "${url}", from: "${from}"), product "${product}"`;
}

/** Comment lines above the file. Asset ids are left out: paths and URIs are already escaped. */
function header(
  uri: string,
  platform: NativePrototypePlatform,
  assets: readonly SourceAsset[],
  context: { spec: ShownSpecJson; revision: number; frame: DeviceFrame; version: string },
): string[] {
  const { spec } = context;
  const capabilities = requiredPrototypeCapabilities(spec);
  const assetLines =
    assets.length === 0
      ? ["Assets: none"]
      : [
          "Assets (not inlined; add each file at its path, a saved prototype serves its bytes):",
          ...assets.map((asset) => `  ${asset.kind} ${asset.path} <- ${asset.uri}`),
        ];
  return [
    `Generated by ${uri} (revision ${context.revision}, frame ${context.frame.id}).`,
    libraryLine(library(platform, context.version)),
    `Required capabilities: ${capabilities.length === 0 ? "none" : capabilities.join(", ")}`,
    ...assetLines,
  ];
}

/** One prototype revision as a single Compose or SwiftUI file sized for a device frame. */
export function readPrototypeSourceResource(
  source: PrototypeSpecRevisionSource,
  format: PrototypeSourceFormat,
  query: PrototypeSourceResourceQuery,
  rendererVersion: string,
): PrototypeSourceResource {
  const { platform, mimeType, render } = FORMATS[format];
  const shown = source.revision(query.id, parsePrototypeRevision(query.revision));
  // The format fixes the platform, so its default frame is the closest known profile.
  const frame = deviceFrameOrThrow(query.frame ?? defaultDeviceFrameId(platform));
  rejectUnexportableSpec(shown.spec, platform);
  const assets = sourceAssets(platform, query.id, shown.spec);
  if (platform === "ios") {
    rejectSwiftEquivalentIds(assets);
  }
  const uri = prototypeResourceUri(query.id, format);
  const text = render({
    id: query.id,
    directory: prototypeDirectoryName(query.id),
    typeName: prototypeHostTypeName(query.id),
    assets,
    storage: shown.spec.storage !== undefined,
    inline: {
      spec: JSON.stringify(shown.spec),
      generatedBy: uri,
      header: header(uri, platform, assets, {
        spec: shown.spec,
        revision: shown.revision,
        frame,
        version: rendererVersion,
      }),
      preview: {
        name: frame.label,
        widthDp: frame.screen.widthDp,
        heightDp: frame.screen.heightDp,
      },
    },
  });
  const { deviceRevision } = shown;
  return {
    text,
    mimeType,
    meta: {
      revision: shown.revision,
      ...(deviceRevision === undefined ? {} : { deviceRevision }),
      revisions: source.history(query.id).map((entry) => entry.revision),
      frame: frame.id,
      sha256: createHash("sha256").update(text, "utf8").digest("hex"),
      rendererVersion,
    },
  };
}
