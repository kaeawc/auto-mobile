// Generated by compiling the production Swift PerfTiming/WebSocketResponse models and
// encoding WebSocketResponse.withPerfTiming with JSONEncoder (.sortedKeys/.prettyPrinted).
// This is real encoder output, not a captured simulator response.
const message: WebSocketMessage = response;
const device = { deviceId: "gesture-diagnostics", platform: "ios", name: "Fake iPhone" } as const;

/** A gesture runner that records the runner's phase timing, then fails like the 5s deadline reply. */
class ThrowingSwipeRunner implements TalkBackSwipeRunner {
  async executeSwipeGesture({ perf }: SwipeGestureRequest): Promise<SwipeResult> {
    perf?.addExternalTiming("iosPerf", response.perfTiming);
    throw new Error(`${message.error}; ${gesturePhaseSummary(message.perfTiming)}`);
  }
}

function swipeOnWithThrowingRunner(): SwipeOn {
  const observation = {
    ...loadIosRemindersNoiseObservePair().after,
    systemInsets: { top: 0, right: 0, bottom: 0, left: 0 },
  };
  const observeScreen = new FakeObserveScreen();
  observeScreen.setObserveResult(observation);
  const timer = new FakeTimer();
  timer.enableAutoAdvance();
  const action = new SwipeOn(device, null, {
    observeScreen,
    scrollables: new FakeScrollableElementsQuery(),
    timer,
    voiceOverExecutor: new ThrowingSwipeRunner(),
    accessibilityDetector: new FakeAccessibilityDetector(),
  });
  action.observedInteraction = runBlockWithEnvelope(() => observation, { observation });
  return action;
}

afterEach(() => setDebugPerfEnabled(false));

describe("iOS gesture phase diagnostics", () => {
  test("bound error preserves the running phase without a perf tree", () => {
    const error =
      "Command request_swipe exceeded execution bound 4500ms in phase xcuitestGesture after 4502ms; XCUITest call is still executing and the runner stays busy until it returns";
    expect(
      decodeCtrlProxyMessage({ type: "swipe_result", requestId: "bound", success: false, error })
        ?.result,
    ).toMatchObject({ success: false, error });
  });

  test("real encoder fixture retains children and adds summary to the deadline error", () => {
    const decoded = decodeCtrlProxyMessage(message);
    expect(decoded?.result).toMatchObject({
      success: false,
      perfTiming: message.perfTiming,
      error: `${message.error}; ${gesturePhaseSummary(message.perfTiming)}`,
    });
    expect(gesturePhaseSummary(message.perfTiming)).toContain("xcuitestGestureMs=5200");
    expect(gesturePhaseSummary(undefined)).toBeUndefined();
  });

  test("failed swipe retains runner phases in requested tool timing output", async () => {
    const timer = new FakeTimer();
    const manager = new RequestManager(timer);
    const perf = createPerformanceTracker(true, timer);
    perf.serial("swipeOn");
    const socket = new FakeOpenSocket((data) => {
      const request: { requestId: string } = JSON.parse(data);
      const decoded = decodeCtrlProxyMessage({ ...message, requestId: request.requestId });
      manager.resolve(request.requestId, decoded?.result);
    });
    const gestures = new CtrlProxyGestures({
      timer,
      requestManager: manager,
      getWebSocket: () => socket,
      ensureConnected: async () => true,
      cancelScreenshotBackoff() {},
    });
    const result = await gestures.requestSwipe({
      x1: 1,
      y1: 2,
      x2: 3,
      y2: 4,
      duration: 300,
      timeoutMs: 5000,
      perf,
    });
    perf.end();
    expect(result.success).toBe(false);
    const finalized = finalizeToolResponse(
      createStructuredToolResponse({
        success: false,
        error: result.error,
        timing: perf.getTimings(),
      }),
      { name: "swipeOn" },
    );
    expect(JSON.stringify(getStructuredPayload(finalized))).toContain('"name":"gesturePhases"');
    expect(getStructuredField(finalized, "timing")).toEqual(perf.getTimings());
    expect(JSON.stringify(getStructuredPayload(finalized))).toContain('"durationMs":5200');
  });

  test("SwipeOn failure catch retains requested timing without a post-gesture observation", async () => {
    setDebugPerfEnabled(true);
    // Exercise the real failure handler of a real SwipeOn; only the gesture runner is fake.
    const action = swipeOnWithThrowingRunner();
    const result = await action.execute({ direction: "up", autoTarget: false });
    expect(result.success).toBe(false);
    expect(JSON.stringify(result.timing)).toContain('"name":"gesturePhases"');
    const finalized = finalizeToolResponse(createStructuredToolResponse(result), {
      name: "swipeOn",
    });
    expect(getStructuredField(finalized, "timing")).toEqual(result.timing);
    setDebugPerfEnabled(false);
    const withoutTiming = await action.execute({
      direction: "up",
      autoTarget: false,
    });
    expect(withoutTiming).not.toHaveProperty("timing");
  });

  test("late reply warns with phases after the request timer removed pending state", async () => {
    const timer = new FakeTimer();
    const client = IOSCtrlProxyClient.createForTesting(device, 8765, {
      wsFactory: createSuccessWebSocketFactory(timer),
      timer,
    });
    const hooks = client.connectionTestHooks;
    const warn = spyOn(logger, "warn").mockImplementation(() => {});
    const debug = spyOn(logger, "debug").mockImplementation(() => {});
    try {
      const pending = hooks.requestManager.register(
        message.requestId ?? "phase-swipe",
        "swipe",
        5000,
        { timeoutErrorFactory: () => ({ success: false, error: "Swipe timed out after 5000ms" }) },
      );
      timer.advanceTime(5000);
      await pending;
      warn.mockClear();
      void hooks.deliverMessage(JSON.stringify(message));
      expect(warn).toHaveBeenCalledTimes(1);
      expect(warn.mock.calls[0]?.[0]).toContain("xcuitestGestureMs=5200");
      expect(warn.mock.calls[0]?.[0]).toContain("lateResponse=true");
      void hooks.deliverMessage(JSON.stringify({ ...message, perfTiming: undefined }));
      expect(warn).toHaveBeenCalledTimes(1);
    } finally {
      warn.mockRestore();
      debug.mockRestore();
      await client.close();
    }
  });

  test("pending failed reply logs its phase summary at debug", async () => {
    const timer = new FakeTimer();
    const client = IOSCtrlProxyClient.createForTesting(device, 8765, {
      wsFactory: createSuccessWebSocketFactory(timer),
      timer,
    });
    const hooks = client.connectionTestHooks;
    const debug = spyOn(logger, "debug").mockImplementation(() => {});
    try {
      const pending = hooks.requestManager.register(
        message.requestId ?? "phase-swipe",
        "swipe",
        5000,
        { timeoutErrorFactory: () => ({ success: false, error: "Swipe timed out" }) },
      );
      void hooks.deliverMessage(JSON.stringify(message));
      expect(await pending).toMatchObject({ success: false, perfTiming: message.perfTiming });
      expect(
        debug.mock.calls.some(
          ([line]) => typeof line === "string" && line.includes("xcuitestGestureMs=5200"),
        ),
      ).toBe(true);
    } finally {
      debug.mockRestore();
      await client.close();
    }
  });
});
